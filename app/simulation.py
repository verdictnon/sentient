def write_run(folder, video_id, geometry_id, rows, events, key=None):
    """Save the clip's run exactly as a finished live session is saved."""
    key = key or uuid.uuid4().hex
    target = Path(folder) / key
    target.mkdir(parents=True, exist_ok=True)
    with (target / "observations.jsonl").open("w", encoding="utf-8") as output:
        for row in rows:
            output.write(json.dumps(row) + "\n")
    summary = dict(
        id=key,
        video_id=video_id,
        geometry_id=geometry_id,
        status="completed",
        error=None,
        processed_frames=len(rows),
        scored_windows=len(rows),
        unique_tracks=len({t["local_track_id"] for r in rows for t in r["tracks"]}),
        threshold=THRESHOLD,
        pickups=events,
        elapsed_seconds=CLIP_SECONDS,
        model_id=MODEL_ID,
        execution="simulated run; no detector or action model was executed",
        simulated=True,
    )
    (target / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return key


