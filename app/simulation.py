def arrivals(rng, day, volume=1.0):
    weekend = day.weekday() >= 5
    curve = WEEKEND_CURVE if weekend else WEEKDAY_CURVE
    scale = DAY_SCALE[day.weekday()] * volume * rng.uniform(0.94, 1.06)
    times = []
    for hour, rate in curve.items():
        offset = (hour - OPEN_HOUR) * 3600
        expected = rate * scale
        count = max(0, round(rng.gauss(expected, math.sqrt(expected))))
        times.extend(offset + rng.uniform(0, 3600) for _ in range(count))
    return sorted(times)


def simulate_day(day, volume=1.0, scripted=()):
    """Generate one trading day; the same date always produces the same people."""
    rng = random.Random(f"sentient-simulated-store/{day.isoformat()}")
    kind = "weekend" if day.weekday() >= 5 else "weekday"
    shoppers = []
    for key, enter in enumerate(arrivals(rng, day, volume), 1):
        shopper = plan_shopper(rng, key, enter)
        roll = rng.random()
        if shopper.items and roll < 0.006:
            shopper.scenario = "no_checkout"
        elif not shopper.items:
            shopper.scenario = "browse_out"
        if rng.random() < 0.009 and shopper.picks:
            shopper.switch_at = shopper.picks[0].t + rng.uniform(6, 30)
        shoppers.append(shopper)
    for script in scripted:
        shoppers.append(script(rng, len(shoppers) + 1))
    finish_shopping(shoppers, rng, kind)
    return shoppers


def track_box(x, y, rng=None):
    jitter = (lambda: rng.uniform(-1.6, 1.6)) if rng else (lambda: 0.0)
    return [
        round(x - 15 + jitter(), 1),
        round(y - 46 + jitter(), 1),
        round(x + 15 + jitter(), 1),
        round(y + jitter(), 1),
    ]


def clamp_point(x, y):
    return min(WIDTH - 1.0, max(1.0, x)), min(HEIGHT - 1.0, max(1.0, y))


def candidates(rng, shopper, day_key, identify):
    """Turn real and false pickups into the model-shaped candidates the app reviews."""
    events = []
    for index, pick in enumerate(shopper.picks):
        if rng.random() > 0.74 and not pick.certain:
            continue
        ms = int(pick.t * 1000)
        events.append(
            dict(
                id=f"sim:{day_key}:{shopper.key}:{index}",
                local_track_id=identify(pick.t),
                start_media_ms=ms,
                end_media_ms=ms,
                detected_media_ms=ms,
                score=round(rng.uniform(THRESHOLD, 0.999), 3),
                status="simulated_prediction",
            )
        )
    return events


def sample_rows(shoppers, start_s, end_s, step_ms, day_key, seed, offset_s=0.0):
    """Sample every shopper on the camera clock into the live observation format."""
    rng = random.Random(f"{seed}/{day_key}/{start_s}/{step_ms}")
    step = step_ms / 1000
    count = int((end_s - start_s) / step)
    rows = [
        dict(frame_index=i, media_ms=float(i * step_ms), tracks=[]) for i in range(count)
    ]
    events = []
    numbering = {}

    def identity(shopper, t):
        late = shopper.switch_at is not None and t >= shopper.switch_at
        key = (shopper.key, late)
        if key not in numbering:
            numbering[key] = len(numbering) + 1
        return f"local:{numbering[key]}"

    order = sorted(shoppers, key=lambda s: s.enter)
    for shopper in order:
        first = max(start_s, shopper.enter)
        last = min(end_s - step, shopper.leave)
        if last < first:
            continue
        index = int(math.ceil((first - start_s) / step))
        stop = int((last - start_s) / step)
        points = shopper.points
        times = shopper._times()
        cursor = 1
        total = len(points)
        offset_x, offset_y = shopper.offset
        lost_until = -1
        for i in range(index, stop + 1):
            t = start_s + i * step
            while cursor < total and times[cursor] <= t:
                cursor += 1
            if cursor >= total:
                x, y = points[-1][1:]
            else:
                t0, x0, y0 = points[cursor - 1]
                t1, x1, y1 = points[cursor]
                ratio = (t - t0) / (t1 - t0) if t1 > t0 else 0
                x = x0 + (x1 - x0) * ratio
                y = y0 + (y1 - y0) * ratio
            if shopper.switch_at is not None and shopper.switch_at <= t < shopper.switch_at + 2.2:
                continue
            if i < lost_until:
                continue
            roll = rng.random()
            if roll < 0.0015:
                lost_until = i + int(1.4 / step)
                continue
            box = track_box(x, y, rng if step_ms >= 1000 else None)
            status = "predicted" if roll < 0.012 else "observed"
            rows[i]["tracks"].append(
                dict(
                    local_track_id=identity(shopper, t),
                    position_status=status,
                    box=box,
                    score=round(0.62 + 0.36 * rng.random(), 2) if status == "observed" else None,
                )
            )
        for event in candidates(rng, shopper, day_key, lambda t: identity(shopper, t)):
            at = event["detected_media_ms"] / 1000
            if not start_s <= at < end_s:
                continue
            tick = int((at - start_s) / step)
            ms = float(tick * step_ms)
            rows_tick = rows[min(tick, count - 1)]
            match = next(
                (t for t in rows_tick["tracks"] if t["local_track_id"] == event["local_track_id"]),
                None,
            )
            if match is None:
                continue
            event["detected_media_ms"] = ms
            event["end_media_ms"] = ms + 400.0
            event["start_media_ms"] = max(0.0, ms - 2400.0)
            events.append(event)
    events.sort(key=lambda e: e["detected_media_ms"])
    return rows, events, dict(numbering)


