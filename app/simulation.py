def _nodes():
    rails = (124, 500)
    aisles = (178, 402, 626, 850, 1098)
    nodes = {}
    for y in rails:
        for x in (96, 178, 300, 402, 520, 626, 740, 850, 980, 1098, 1186):
            nodes[f"r{y}-{x}"] = (x, y)
    for x in aisles:
        for y in (220, 312, 404):
            nodes[f"a{x}-{y}"] = (x, y)
    edges = {key: {} for key in nodes}

    def link(a, b):
        distance = math.dist(nodes[a], nodes[b])
        edges[a][b] = distance
        edges[b][a] = distance

    for y in rails:
        row = (96, 178, 300, 402, 520, 626, 740, 850, 980, 1098, 1186)
        for a, b in zip(row, row[1:]):
            link(f"r{y}-{a}", f"r{y}-{b}")
    for x in aisles:
        chain = [f"r124-{x}", f"a{x}-220", f"a{x}-312", f"a{x}-404", f"r500-{x}"]
        for a, b in zip(chain, chain[1:]):
            link(a, b)
    return nodes, edges


NODES, EDGES = _nodes()
PATH_CACHE = {}


def nearest_node(point):
    return min(NODES, key=lambda key: math.dist(NODES[key], point))


def shortest_path(start, goal):
    if start == goal:
        return [start]
    cached = PATH_CACHE.get((start, goal))
    if cached:
        return cached
    queue = [(0.0, start, None)]
    parents = {}
    while queue:
        cost, key, parent = heappop(queue)
        if key in parents:
            continue
        parents[key] = parent
        if key == goal:
            break
        for neighbour, step in EDGES[key].items():
            if neighbour not in parents:
                heappush(queue, (cost + step, neighbour, key))
    path = [goal]
    while parents[path[-1]] is not None:
        path.append(parents[path[-1]])
    path.reverse()
    PATH_CACHE[start, goal] = path
    return path


def walk_points(start, goal):
    """Corridor waypoints between two free points on the floor."""
    route = shortest_path(nearest_node(start), nearest_node(goal))
    return [start] + [NODES[key] for key in route] + [goal]


