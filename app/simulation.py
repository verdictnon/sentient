@dataclass
class Pick:
    t: float
    zone: str
    real: bool
    certain: bool = False


@dataclass
class Shopper:
    key: int
    enter: float
    speed: float
    offset: tuple
    colour: tuple
    points: list = field(default_factory=list)
    picks: list = field(default_factory=list)
    items: int = 0
    scenario: str = "normal"
    queue_enter: float | None = None
    service_start: float | None = None
    service_end: float | None = None
    till: int = 0
    switch_at: float | None = None
    leave: float = 0.0
    priority: bool = False

    def go(self, x, y, wait=0.0, speed=None):
        last = self.points[-1]
        distance = math.dist(last[1:], (x, y))
        arrive = last[0] + distance / (speed or self.speed)
        self.points.append((arrive, x, y))
        if wait:
            self.points.append((arrive + wait, x, y))
        return self.points[-1][0]

    def walk(self, goal, wait=0.0):
        start = self.points[-1][1:]
        for x, y in walk_points(start, goal)[1:-1]:
            self.go(x, y)
        return self.go(goal[0], goal[1], wait)

    def position(self, t):
        times = self._times()
        index = bisect_right(times, t)
        if index <= 0:
            return self.points[0][1:]
        if index >= len(self.points):
            return self.points[-1][1:]
        t0, x0, y0 = self.points[index - 1]
        t1, x1, y1 = self.points[index]
        ratio = (t - t0) / (t1 - t0) if t1 > t0 else 0
        return (x0 + (x1 - x0) * ratio, y0 + (y1 - y0) * ratio)

    def _times(self):
        cached = getattr(self, "_cached_times", None)
        if cached is None or len(cached) != len(self.points):
            cached = [p[0] for p in self.points]
            self._cached_times = cached
        return cached


def queue_slot(index):
    if index <= 8:
        return (622 - index * 30, 612)
    return (382, 612 - (index - 8) * 30)


def choose_stops(rng, persona):
    wanted = {"quick": 1.8, "regular": 3.8, "big": 6.5, "browser": 1.8}[persona]
    base = sum(v[0] for v in STOP_ZONES.values())
    scale = wanted / base
    chosen = [z for z, v in STOP_ZONES.items() if rng.random() < min(0.95, v[0] * scale)]
    if not chosen:
        chosen = [rng.choices(list(STOP_ZONES), [v[0] for v in STOP_ZONES.values()])[0]]
    chosen.sort(key=LOOP_ORDER.index)
    return chosen


def plan_shopper(rng, key, enter):
    persona = rng.choices(("quick", "regular", "big", "browser"), (0.32, 0.43, 0.13, 0.12))[0]
    speed = rng.uniform(46, 70)
    offset = (rng.uniform(-11, 11), rng.uniform(-9, 9))
    colour = rng.choice(PALETTE)
    shopper = Shopper(key, enter, speed, offset, colour)
    door = 155 + rng.uniform(-30, 30)
    shopper.points = [(enter, door, 716.0)]
    shopper.go(door, 640, speed=DOOR_SPEED)
    shopper.go(178 + offset[0], 500 + offset[1])
    for zone in choose_stops(rng, persona):
        share, median, pick = STOP_ZONES[zone]
        point = stop_point(rng, zone)
        dwell = max(3.0, rng.lognormvariate(math.log(median), 0.55))
        arrive = shopper.walk(point)
        shopper.points.append((arrive + dwell, point[0], point[1]))
        chance = 0.0 if persona == "browser" else pick
        if rng.random() < chance:
            shopper.items += rng.choice((1, 1, 1, 2, 2, 3))
            shopper.picks.append(Pick(arrive + dwell * rng.uniform(0.45, 0.9), zone, True))
    return shopper


def leave_by_entrance(shopper):
    door = 155 + (shopper.key % 40) - 20
    shopper.walk((178, 500))
    shopper.go(door, 640)
    shopper.go(door, 716, speed=DOOR_SPEED)
    shopper.leave = shopper.points[-1][0]


def till_open(day_kind, till, t, day_start):
    if till == 0:
        return True
    hour = (t - day_start) / 3600 + OPEN_HOUR
    windows = ((12.4, 13.6), (18.3, 20.5)) if day_kind == "weekday" else ((11.5, 14.0), (17.5, 20.0))
    return any(a <= hour < b for a, b in windows)


def finish_shopping(shoppers, rng, day_kind):
    """Run the single FIFO line and turn it into positions at the tills."""
    buyers = []
    for shopper in shoppers:
        if shopper.priority:
            # Scripted buyers use the staff-assisted lane so the clip shows a payment.
            shopper.go(330, 640)
            shopper.go(620, 574)
            shopper.go(706, 574, 18)
            shopper.go(830, 574)
            shopper.go(1095, 640)
            shopper.go(1095, 716, speed=DOOR_SPEED)
            shopper.leave = shopper.points[-1][0]
        elif shopper.scenario in ("browse_out", "no_checkout"):
            leave_by_entrance(shopper)
        elif not shopper.items:
            leave_by_entrance(shopper)
        else:
            arrive = shopper.walk((520 + shopper.offset[0], 500 + shopper.offset[1]))
            shopper.queue_enter = arrive
            buyers.append(shopper)
    buyers.sort(key=lambda s: s.queue_enter)
    till_free = [0.0, 0.0]
    line = []
    served = []
    for shopper in buyers:
        arrive = shopper.queue_enter
        ahead = [s for s in line if s.service_start > arrive]
        line = ahead
        candidates = []
        for index in (0, 1):
            start = max(arrive, till_free[index])
            while not till_open(day_kind, index, start, 0.0):
                start += 120.0
                if start > arrive + 3600:
                    break
            candidates.append((start, index))
        start, index = min(candidates)
        patience = rng.uniform(300, 640)
        if start - arrive > patience and rng.random() < 0.1:
            shopper.scenario = "abandoned"
            shopper.queue_enter = None
            shopper.walk((470 + shopper.offset[0], 620), rng.uniform(40, 120))
            leave_by_entrance(shopper)
            continue
        shopper.service_start = start
        shopper.till = index
        shopper.service_end = start + (30 + 9 * shopper.items) * rng.uniform(0.75, 1.3)
        till_free[index] = shopper.service_end
        line.append(shopper)
        served.append(shopper)
    for shopper in served:
        slots = sorted(
            s.service_start
            for s in served
            if s.queue_enter < shopper.queue_enter and s.service_start > shopper.queue_enter
        )
        position = len(slots)
        x, y = queue_slot(position)
        shopper.go(x, y)
        moment = shopper.points[-1][0]
        for step in slots:
            if step <= moment:
                position -= 1
                continue
            hold = step
            shopper.points.append((hold, x, y))
            position = max(0, position - 1)
            x, y = queue_slot(position)
            moment = hold + 1.6
            shopper.points.append((moment, x, y))
        lane = 640 if shopper.till == 0 else 574
        shopper.points.append((max(shopper.service_start, shopper.points[-1][0]), x, y))
        shopper.go(706, lane)
        shopper.points.append((max(shopper.service_end, shopper.points[-1][0] + 8), 706, lane))
        shopper.go(830, lane)
        shopper.go(1095 + shopper.offset[0], 640)
        shopper.go(1095 + shopper.offset[0], 716, speed=DOOR_SPEED)
        shopper.leave = shopper.points[-1][0]


